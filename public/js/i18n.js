  t(key) {
    const lang = this.currentLang;
    return (this.translations[lang] && this.translations[lang][key]) || this.translations['en'][key] || key;
  },

  setLanguage(lang) {
    if (!this.translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('maicon_lang', lang);
    document.documentElement.lang = lang;
    this.applyTranslations();
  },

  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) {
        if (el.getAttribute('data-i18n-html') === 'true') {
          el.innerHTML = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) {
        el.placeholder = translation;
      }
    });

    const langLabel = document.getElementById('current-lang-label');
    const langFlag = document.getElementById('current-lang-flag');
    if (langLabel) {
      langLabel.textContent = this.currentLang === 'fr' ? 'Français' : 'English';
    }
    if (langFlag) {
      langFlag.textContent = this.currentLang === 'fr' ? '🇫🇷' : '🇺🇸';
    }

    if (typeof renderCategoryPills === 'function') {
      renderCategoryPills();
    }
    if (typeof fetchAndRenderProducts === 'function') {
      fetchAndRenderProducts();
    }
    if (typeof renderCartDrawer === 'function') {
      renderCartDrawer();
    }
  }
